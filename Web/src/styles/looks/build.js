/**
 * The look generator's core: packs in, CSS text and resolved values out.
 *
 * Pure (no fs), so scripts/build-looks.mjs writes what this returns and the
 * tests check the committed file against it (looks.drift.test.js).
 *
 * Selector scheme — why each block is written the way it is:
 *
 *   DEFAULT look (prime-time since Phase 6) keeps the exact selectors index.css used,
 *   so a page with no `data-look` at all (unit tests, a stray document) still
 *   gets every token:
 *       :root, [data-appearance="dark"]        :root has the dark values
 *       [data-appearance="light"]
 *       [data-role="player"]                   role palettes, on <html>
 *   plus a `[data-look="<default>"]`-qualified twin of each, so a default-look island
 *   inside another look's page wins over that page (0,2,0 beats 0,1,0).
 *
 *   OTHER looks are qualified, and come later in the file:
 *       [data-look="L"][data-appearance="dark"]             <html> itself (0,2,0)
 *       :where([data-look="L"]) [data-appearance="dark"]    an island inside (0,1,0,
 *                                                           later than the default's)
 *       [data-look="L"][data-role="player"]
 *
 *   Every derived token is re-declared in each appearance block — a custom
 *   property that references another is resolved where it is declared, so a
 *   token computed once on <html> would carry the page's appearance into an
 *   island (the rule index.css already followed).
 *
 * Role tokens are emitted as --role-dark, --role-dark-fg, --ident-dark,
 * --ident-dark-fg (and -light); each appearance block points --accent,
 * --accent-fg, --ident and --ident-fg at its own half.
 */
import { APPEARANCES, APPEARANCE_TOKENS, DURATION_STEPS, LOOK_TOKENS, ROLES, ROLE_TOKENS } from './contract.js';
import { parseColor, toHex, toTriplet } from './color.js';

const q = (id) => `[data-look="${id}"]`;

const ROLE_VAR = {
  accent: (a) => `role-${a}`,
  'accent-fg': (a) => `role-${a}-fg`,
  ident: (a) => `ident-${a}`,
  'ident-fg': (a) => `ident-${a}-fg`,
};

const fmt = (type, value) => (type === 'triplet' ? toTriplet(value) : String(value));

const ordered = (spec, values, where) => {
  for (const key of Object.keys(values)) {
    if (!(key in spec)) throw new Error(`${where}: "${key}" is not a contract token (src/styles/looks/contract.js)`);
  }
  return Object.keys(spec).filter((k) => k in values).map((k) => [k, fmt(spec[k].type, values[k])]);
};

/** The appearance tokens a look declares for one appearance, in contract order. */
export const appearanceTokens = (look, appearance) => {
  const values = {
    accent: `var(--${ROLE_VAR.accent(appearance)})`,
    'accent-fg': `var(--${ROLE_VAR['accent-fg'](appearance)})`,
    ident: `var(--${ROLE_VAR.ident(appearance)})`,
    'ident-fg': `var(--${ROLE_VAR['ident-fg'](appearance)})`,
    ...(look.shared || {}),
    ...(look.appearances?.[appearance] || {}),
  };
  return ordered(APPEARANCE_TOKENS, values, `${look.id}.${appearance}`);
};

/** The role variables a look declares for one role: [['role-dark', '…'], …]. */
export const roleVars = (look, role) => {
  const out = [];
  for (const appearance of APPEARANCES) {
    const values = look.roles?.[role]?.[appearance] || {};
    for (const [key, value] of ordered(ROLE_TOKENS, values, `${look.id}.roles.${role}.${appearance}`)) {
      out.push([ROLE_VAR[key](appearance), value]);
    }
  }
  return out;
};

export const lookTokens = (look) => ordered(LOOK_TOKENS, look.look || {}, `${look.id}.look`);

const block = (selectors, decls, props = []) => [
  `${selectors.join(',\n')} {`,
  ...props.map(([p, v]) => `  ${p}: ${v};`),
  ...decls.map(([k, v]) => `  --${k}: ${v};`),
  '}',
].join('\n');

const MOTION_ZERO = [['duration-default', '0ms'], ...DURATION_STEPS.map((s) => [`duration-${s}`, '0ms']),
  ...[1, 2, 3, 4].map((n) => [`dur-${n}`, '0ms'])];

/**
 * @param {object[]} looks resolved packs, the default first
 * @param {string} defaultId
 * @returns {string} the CSS for src/styles/generated/looks.css
 */
export const buildLooksCss = (looks, defaultId) => {
  const parts = [
    '/*',
    ' * GENERATED by scripts/build-looks.mjs from src/styles/looks/*.js — do not edit.',
    ' * Run `npm run looks` after changing a pack; looks.drift.test.js fails if this',
    ' * file and the packs disagree. See docs/design-language/PLAN.md §4.',
    ' */',
  ];
  const sorted = [...looks].sort((a, b) => (a.id === defaultId ? -1 : b.id === defaultId ? 1 : 0));

  for (const look of sorted) {
    const isDefault = look.id === defaultId;
    const L = q(look.id);
    parts.push('', `/* ── look: ${look.id}${isDefault ? ' (default)' : ''} ── */`);

    // Look-wide tokens and the public (no role) palette.
    parts.push(block(isDefault ? [':root', L] : [L], [...lookTokens(look), ...roleVars(look, 'public')]));

    for (const role of ROLES.filter((r) => r !== 'public')) {
      const sel = isDefault ? [`[data-role="${role}"]`, `${L}[data-role="${role}"]`] : [`${L}[data-role="${role}"]`];
      parts.push(block(sel, roleVars(look, role)));
    }

    for (const appearance of APPEARANCES) {
      const A = `[data-appearance="${appearance}"]`;
      let sel;
      if (isDefault) {
        sel = appearance === 'dark' ? [':root', A, `${L}${A}`] : [A, `${L}${A}`];
      } else {
        sel = [`${L}${A}`, ...(appearance === 'dark' ? [`${L}:not([data-appearance])`] : []), `:where(${L}) ${A}`];
      }
      parts.push(block(sel, appearanceTokens(look, appearance), [['color-scheme', appearance]]));
    }

    if (look.reduceMotion) {
      const sel = isDefault ? [':root', L] : [L];
      parts.push(`@media (prefers-reduced-motion: reduce) {\n${block(sel, MOTION_ZERO).replace(/^/gm, '  ')}\n}`);
    }
  }
  return `${parts.join('\n')}\n`;
};

/**
 * Every token as an element with this look, appearance and role would compute
 * it, var() references substituted. For the tests; mirrors the cascade above.
 * @returns {Record<string, string>} name (no `--`) → resolved CSS text
 */
export const resolveTokens = (look, appearance, role = 'public') => {
  const vars = Object.fromEntries([
    ...lookTokens(look),
    ...roleVars(look, 'public'),
    ...(role === 'public' ? [] : roleVars(look, role)),
    ...appearanceTokens(look, appearance),
  ]);
  const resolve = (value, depth = 0) => {
    if (depth > 20) throw new Error(`var() cycle near ${value}`);
    return value.replace(/var\(--([\w-]+)\)/g, (_, name) => {
      if (!(name in vars)) throw new Error(`${look.id}/${appearance}/${role}: var(--${name}) is not defined`);
      return resolve(vars[name], depth + 1);
    });
  };
  return Object.fromEntries(Object.entries(vars).map(([k, v]) => [k, resolve(v)]));
};

/** Resolved hex of a colour token (opaque colours only), for meta and THEME_COLOR. */
export const tokenHex = (look, appearance, name, role = 'public') =>
  toHex(parseColor(resolveTokens(look, appearance, role)[name]));

/** looks.meta.json: per look × appearance, the page and surface colours. */
export const buildLooksMeta = (looks, defaultId) => ({
  generatedBy: 'scripts/build-looks.mjs',
  default: defaultId,
  looks: Object.fromEntries(looks.map((look) => [look.id, Object.fromEntries(APPEARANCES.map((a) => [a,
    Object.fromEntries(['bg', 'surface', 'surface-raised', 'surface-sunken', 'surface-overlay', 'accent']
      .map((name) => [name, tokenHex(look, a, name)])),
  ]))])),
});
