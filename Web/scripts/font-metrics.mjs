#!/usr/bin/env node
/**
 * npm run fonts:metrics — measure the look fonts against local fallbacks and
 * write src/styles/fonts-fallback.css (docs/design-language/PLAN.md §5.4).
 *
 * While a web font downloads, text is drawn in a fallback. If the fallback is
 * wider or taller, lines re-wrap when the font arrives and the page jumps (CLS).
 * A metric-matched fallback is the local font scaled (`size-adjust`) to the web
 * font's average width, with the web font's ascent and descent, so the swap
 * moves nothing.
 *
 * Measured in Chromium with canvas text metrics on the real woff2 files (no font
 * parsing dependency): width of a representative sample at 100px, and
 * fontBoundingBoxAscent/Descent. Re-run only when a font file or the fallback
 * changes; the output is committed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../src/styles/fonts-fallback.css');

const file = (spec) => fs.readFileSync(require.resolve(spec)).toString('base64');

/* What each web font is matched against, and the text it is matched on. */
const TARGETS = [
  {
    family: 'Archivo Fallback',
    webFont: { name: 'Archivo Variable', data: file('@fontsource-variable/archivo/files/archivo-latin-wdth-normal.woff2'), weight: 400 },
    local: ['Arial', 'Helvetica Neue', 'Helvetica', 'Roboto'],
    measureWith: 'Arial',
    sample: 'The judges score each routine for difficulty, combination and execution: 9.85 Mallakhamb India',
  },
  {
    family: 'Teko Fallback',
    webFont: { name: 'Teko', data: file('@fontsource/teko/files/teko-latin-600-normal.woff2'), weight: 600 },
    local: ['Arial', 'Helvetica Neue', 'Helvetica', 'Roboto'],
    measureWith: 'Arial',
    sample: 'MALLAKHAMB INDIA POLE ROPE HANGING 0123456789 FINAL SCORE',
  },
];

const browser = await chromium.launch();
const page = await browser.newPage();
await page.setContent('<html><body></body></html>');

const results = [];
for (const t of TARGETS) {
  const r = await page.evaluate(async ({ webFont, measureWith, sample }) => {
    const face = new FontFace('__probe', `url(data:font/woff2;base64,${webFont.data})`, { weight: String(webFont.weight) });
    await face.load();
    document.fonts.add(face);
    const ctx = document.createElement('canvas').getContext('2d');
    const metrics = (font) => {
      ctx.font = font;
      const m = ctx.measureText(sample);
      return { width: m.width, ascent: m.fontBoundingBoxAscent, descent: m.fontBoundingBoxDescent };
    };
    const local = metrics(`${webFont.weight} 100px "${measureWith}"`);
    const fallbackUsed = document.fonts.check(`100px "${measureWith}"`);
    return { web: metrics(`${webFont.weight} 100px __probe`), local, fallbackUsed };
  }, t);
  const sizeAdjust = r.web.width / r.local.width;
  results.push({
    ...t,
    sizeAdjust: (sizeAdjust * 100).toFixed(2),
    ascent: ((r.web.ascent / sizeAdjust)).toFixed(2),
    descent: ((r.web.descent / sizeAdjust)).toFixed(2),
  });
  console.log(`${t.family}: size-adjust ${(sizeAdjust * 100).toFixed(2)}%  ascent ${r.web.ascent.toFixed(1)}  descent ${r.web.descent.toFixed(1)}  (vs ${t.measureWith})`);
}
await browser.close();

const css = `/*
 * GENERATED by scripts/font-metrics.mjs (npm run fonts:metrics) — do not edit.
 *
 * Metric-matched fallbacks for the look fonts: a local font scaled to the web
 * font's average width, with its ascent and descent, so nothing moves when the
 * web font arrives (CLS 0). Named after the font they stand in for; the look
 * packs list each one right after its web font. Measured against the first
 * local() font; the others are close enough to beat an unmatched fallback.
 */
${results.map((r) => `@font-face {
  font-family: '${r.family}';
  src: ${r.local.map((n) => `local('${n}')`).join(', ')};
  size-adjust: ${r.sizeAdjust}%;
  ascent-override: ${r.ascent}%;
  descent-override: ${r.descent}%;
  line-gap-override: 0%;
}`).join('\n\n')}
`;
fs.writeFileSync(out, css);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
