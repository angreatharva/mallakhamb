#!/usr/bin/env node
'use strict';

/**
 * Which operations of the API spec the recorded corpora exercise, and with
 * which answers. Writes `generated/TWINRUN-COVERAGE.md`.
 *
 *   node twinrun/coverage.js
 *
 * An operation counts as covered when a corpus holds at least one request for
 * it. That is not the same as its happy path being covered: the table also
 * says which operations never answered 2xx in any corpus.
 */

const fs = require('node:fs');
const path = require('node:path');
const { SERVER_ROOT, writeGenerated } = require('../lib/server');
const { listCorpora, readRequests } = require('./lib/corpus');

const spec = JSON.parse(fs.readFileSync(path.join(SERVER_ROOT, 'docs', 'openapi.json'), 'utf8'));

const operations = [];
for (const [template, item] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
    operations.push({
      method: method.toUpperCase(),
      template,
      id: operation.operationId,
      tag: (operation.tags || ['—'])[0],
      params: (template.match(/\{[^}]+\}/g) || []).length,
      pattern: new RegExp(`^${template.replace(/[.*+?^$()|[\]\\]/g, '\\$&').replace(/\{[^}]+\}/g, '[^/]+')}/?$`, 'i'),
      statuses: new Map(), // status → count
      corpora: new Set(),
    });
  }
}
// A literal segment beats a parameter: /teams/submitted before /teams/{id}.
operations.sort((a, b) => a.params - b.params);

function operationFor(method, requestPath) {
  const clean = requestPath.split('?')[0].replace(/^\/api\/v1\//, '/api/');
  return operations.find((operation) => operation.method === method && operation.pattern.test(clean)) || null;
}

const corpora = listCorpora();
const perCorpus = [];
const unmatched = new Map();

for (const name of corpora) {
  const lines = readRequests(name);
  const seen = new Set();
  for (const { request, response } of lines) {
    const operation = operationFor(request.method, request.path);
    if (!operation) {
      const key = `${request.method} ${request.path.split('?')[0].replace(/[0-9a-f]{24}/g, ':id')}`;
      unmatched.set(key, (unmatched.get(key) || 0) + 1);
      continue;
    }
    operation.statuses.set(response.status, (operation.statuses.get(response.status) || 0) + 1);
    operation.corpora.add(name);
    seen.add(operation.id);
  }
  perCorpus.push({ name, requests: lines.length, operations: seen.size });
}

const covered = operations.filter((operation) => operation.corpora.size > 0);
const withSuccess = covered.filter((operation) => [...operation.statuses.keys()].some((status) => status >= 200 && status < 300));
const writes = operations.filter((operation) => operation.method !== 'GET');
const writesWithSuccess = withSuccess.filter((operation) => operation.method !== 'GET');
const statusTotals = new Map();
for (const operation of operations) for (const [status, count] of operation.statuses) statusTotals.set(status, (statusTotals.get(status) || 0) + count);

const code = (text) => `\`${text}\``;
const byTemplate = (a, b) => (a.template < b.template ? -1 : a.template > b.template ? 1 : a.method < b.method ? -1 : 1);
const lines = [
  '# Twin-run corpus coverage',
  '',
  '<!-- GENERATED by tools/node/twinrun/coverage.js. Do not edit. -->',
  '',
  `What the recorded corpora ask of the **${operations.length}** operations in \`Server/docs/openapi.json\`.`,
  '',
  '## Summary',
  '',
  `- Operations with at least one recorded request: **${covered.length} of ${operations.length}**.`,
  `- Operations with a successful (2xx) answer recorded: **${withSuccess.length} of ${operations.length}**.`,
  `- Write operations (POST, PUT, PATCH, DELETE) with a successful answer recorded: **${writesWithSuccess.length} of ${writes.length}**.`,
  `- Requests recorded: **${perCorpus.reduce((n, corpus) => n + corpus.requests, 0)}**.`,
  '',
  '| Corpus | Requests | Operations |',
  '|---|---|---|',
  ...perCorpus.map((corpus) => `| ${code(corpus.name)} | ${corpus.requests} | ${corpus.operations} |`),
  '',
  '| Status | Requests |',
  '|---|---|',
  ...[...statusTotals.entries()].sort((a, b) => a[0] - b[0]).map(([status, count]) => `| ${status} | ${count} |`),
  '',
  '## Operations with no successful answer recorded',
  '',
  'Their refusals and validation errors are recorded, but not what they do when they work. These need a flow that reaches them with valid data.',
  '',
  '| Tag | Method | Path | Statuses recorded |',
  '|---|---|---|---|',
  ...operations
    .filter((operation) => !withSuccess.includes(operation))
    .sort((a, b) => (a.tag < b.tag ? -1 : a.tag > b.tag ? 1 : byTemplate(a, b)))
    .map((operation) => `| ${operation.tag} | ${operation.method} | ${code(operation.template)} | ${[...operation.statuses.keys()].sort().join(', ') || '_none_'} |`),
  '',
  '## Every operation',
  '',
  '| Method | Path | Statuses recorded | Corpora |',
  '|---|---|---|---|',
  ...[...operations].sort(byTemplate).map(
    (operation) =>
      `| ${operation.method} | ${code(operation.template)} | ${[...operation.statuses.entries()].sort((a, b) => a[0] - b[0]).map(([status, count]) => `${status}×${count}`).join(', ') || '_none_'} | ${[...operation.corpora].join(', ')} |`,
  ),
];
if (unmatched.size > 0) {
  lines.push('', '## Recorded requests that match no operation in the spec', '', '| Request | Count |', '|---|---|');
  for (const [key, count] of [...unmatched.entries()].sort()) lines.push(`| ${code(key)} | ${count} |`);
}

const file = writeGenerated('TWINRUN-COVERAGE.md', lines.join('\n'));
console.log(
  `coverage: ${covered.length}/${operations.length} operations asked, ${withSuccess.length} with a 2xx, ` +
    `${writesWithSuccess.length}/${writes.length} writes with a 2xx, ${unmatched.size} request shapes outside the spec → ${file}`,
);
