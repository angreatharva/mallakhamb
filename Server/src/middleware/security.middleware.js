const cors = require('cors');
const rateLimit = require('express-rate-limit');
const { ipKeyGenerator } = require('express-rate-limit');
const { COOKIE_NAMES } = require('../utils/security/cookie.util');
const { AuthorizationError } = require('../errors');

/**
 * Generate a cryptographically secure nonce for CSP.
 * Attached to res.locals.nonce for use in templates/headers.
 * Phase 2A, Item 2.3
 */
function generateNonceMiddleware(req, res, next) {
  res.locals.nonce = crypto.randomBytes(16).toString('base64');
  next();
}

// ---------------------------------------------------------------------------
// Environment-specific rate limit configuration (Requirement 23.6)
// ---------------------------------------------------------------------------
const RATE_LIMIT_CONFIG = {
  production: {
    general: { windowMs: 15 * 60 * 1000, max: 100 },   // 100 req / 15 min
    auth:    { windowMs: 15 * 60 * 1000, max: 10  },   // 10  req / 15 min
    user:    { windowMs: 15 * 60 * 1000, max: 200 }    // 200 req / 15 min (per user)
  },
  staging: {
    general: { windowMs: 15 * 60 * 1000, max: 300 },
    auth:    { windowMs: 15 * 60 * 1000, max: 30  },
    user:    { windowMs: 15 * 60 * 1000, max: 500 }
  },
  development: {
    general: { windowMs: 60 * 1000, max: 1000 },        // 1000 req / 1 min
    auth:    { windowMs: 60 * 1000, max: 200  },
    user:    { windowMs: 60 * 1000, max: 2000 }
  },
  test: {
    general: { windowMs: 60 * 1000, max: 10000 },
    auth:    { windowMs: 60 * 1000, max: 10000 },
    user:    { windowMs: 60 * 1000, max: 10000 }
  }
};

/**
 * Get rate limit config for the current environment.
 * @param {string} nodeEnv - NODE_ENV value
 * @param {'general'|'auth'|'user'} type - Limit type
 * @returns {{ windowMs: number, max: number }}
 */
function getRateLimitConfig(nodeEnv, type) {
  const envConfig = RATE_LIMIT_CONFIG[nodeEnv] || RATE_LIMIT_CONFIG.development;
  return envConfig[type] || envConfig.general;
}

/**
 * Create helmet security headers middleware
 * @param {Object} container - DI container
 * @returns {Function} Express middleware
 */
function createHelmetMiddleware(container) {
  const config = container.resolve('config');
  const isDevelopment = config.get('server.nodeEnv') === 'development';

  // Phase 2A: Use nonces in production, allow unsafe-inline/eval in dev (Vite needs it)
  const scriptSrc = ["'self'", "https://checkout.razorpay.com", "https://cdn.razorpay.com"];
  const styleSrc = ["'self'"];

  if (isDevelopment) {
    scriptSrc.push("'unsafe-inline'", "'unsafe-eval'");
    styleSrc.push("'unsafe-inline'");
  } else {
    // In production, use the nonce generated by generateNonceMiddleware
    scriptSrc.push((req, res) => `'nonce-${res.locals.nonce}'`);
    // Some libraries might still need unsafe-inline for styles, but ideally we'd use nonces there too.
    // We'll allow unsafe-inline for styles until all inline styles are refactored, but script nonces are strictly enforced.
    styleSrc.push("'unsafe-inline'");
  }

  return helmet({
    // Content Security Policy
    contentSecurityPolicy: {
      directives: {
        defaultSrc: ["'self'"],
        styleSrc: styleSrc,
        scriptSrc: scriptSrc,
        // Set explicitly: without it, worker-src falls back to script-src, and
        // script-src has no `blob:` — so a library spawning a worker from a
        // blob URL (Razorpay's checkout does) is blocked. Kept in step with the
        // SPA's own meta CSP in Web/index.html.
        workerSrc: ["'self'", 'blob:'],
        imgSrc: ["'self'", 'data:', 'https:'],
        connectSrc: [
          "'self'",
          'https://api.razorpay.com',
          'https://checkout.razorpay.com',
          'https://lumberjack.razorpay.com'
        ],
        fontSrc: ["'self'", 'data:'],
        objectSrc: ["'none'"],
        mediaSrc: ["'self'"],
        frameSrc: [
          "'self'",
          'https://api.razorpay.com',
          'https://checkout.razorpay.com'
        ]
      }
    },
    // Strict Transport Security (HTTPS only)
    hsts: {
      maxAge: 31536000, // 1 year
      includeSubDomains: true,
      preload: true
    },
    // Prevent clickjacking
    frameguard: {
      action: 'deny'
    },
    // Prevent MIME type sniffing
    noSniff: true,
    // XSS Protection
    xssFilter: true,
    // Hide X-Powered-By header
    hidePoweredBy: true,
    // Referrer Policy
    referrerPolicy: {
      policy: 'strict-origin-when-cross-origin'
    }
  });
}

/**
 * Create CORS middleware with environment-specific settings (Requirement 23.4)
 * - Production: only origins listed in CORS_ORIGINS env var are allowed
 * - Development/test: all origins are allowed
 * @param {Object} container - DI container
 * @returns {Function} Express middleware
 */
function createCorsMiddleware(container) {
  const config = container.resolve('config');
  const logger = container.resolve('logger');
  
  const corsOrigins = config.get('server.corsOrigins');
  const nodeEnv = config.get('server.nodeEnv');
  const isProduction = nodeEnv === 'production' || nodeEnv === 'staging';

  const corsOptions = {
    origin: (origin, callback) => {
      // Allow requests with no origin (mobile apps, Postman, server-to-server)
      if (!origin) {
        return callback(null, true);
      }

      // In production/staging, enforce strict origin whitelist
      if (isProduction) {
        if (corsOrigins && corsOrigins.length > 0 && corsOrigins.includes(origin)) {
          callback(null, true);
        } else {
          logger.warn('CORS blocked request', { origin, nodeEnv });
          // 403, not the 500 a plain Error became: a foreign origin is a refused
          // client, not a server fault, and it must not count as a 5xx
          // (Grafana's "High 5xx"). The request still stops here.
          callback(new AuthorizationError('Not allowed by CORS'));
        }
        return;
      }

      // In development/test, allow all origins
      return callback(null, true);
    },
    credentials: true,
    methods: ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'OPTIONS'],
    allowedHeaders: [
      'Content-Type',
      'Authorization',
      'X-Correlation-ID',
      'X-Request-ID',
      'X-Competition-ID',
      'X-CSRF-Token'
    ],
    exposedHeaders: [
      'X-Correlation-ID',
      'X-Response-Time',
      'X-RateLimit-Limit',
      'X-RateLimit-Remaining',
      'X-RateLimit-Reset',
      'X-New-Token'
    ],
    maxAge: 86400 // 24 hours
  };

  return cors(corsOptions);
}

/**
 * Create rate limiting middleware per IP (Requirement 23.6)
 * Uses environment-specific limits.
 * @param {Object} container - DI container
 * @returns {Function} Express middleware
 */
function createIpRateLimitMiddleware(container) {
  const config = container.resolve('config');
  const logger = container.resolve('logger');
  const nodeEnv = config.get('server.nodeEnv');

  const { windowMs, max } = getRateLimitConfig(nodeEnv, 'general');

  return rateLimit({
    windowMs,
    max,
    message: {
      success: false,
      error: {
        message: 'Too many requests from this IP, please try again later',
        code: 'RATE_LIMIT_EXCEEDED'
      }
    },
    standardHeaders: true, // Return rate limit info in headers
    legacyHeaders: false,
    handler: (req, res) => {
      logger.warn('IP rate limit exceeded', {
        ip: req.ip,
        path: req.path,
        method: req.method,
        nodeEnv
      });
      res.status(429).json({
        success: false,
        error: {
          message: 'Too many requests from this IP, please try again later',
          code: 'RATE_LIMIT_EXCEEDED'
        }
      });
    }
  });
}

/**
 * Create rate limiting middleware per user (Requirement 23.6)
 * Uses environment-specific limits.
 *
 * MED-2: this limiter is mounted at the route-group level (see routes/index.js), which
 * runs BEFORE each router's own authenticate middleware, so `req.user` is not populated
 * yet. The principal is therefore resolved from the access token directly. Verifying the
 * token is a local signature check with no database read, and a forged token cannot mint
 * a fresh bucket: it fails verification, is treated as anonymous (and skipped), and is
 * then rejected with 401 by the route's own auth middleware.
 *
 * Anonymous requests are skipped by design — this limiter must NEVER fall back to an IP
 * key. A venue NATs every judge tablet behind one address, so an IP-keyed limit on
 * authenticated traffic would throttle a live panel. Unauthenticated endpoints are the
 * only place an IP limit belongs (see createIpRateLimitMiddleware).
 *
 * @param {Object} container - DI container
 * @returns {Function} Express middleware
 */
function createUserRateLimitMiddleware(container) {
  const config = container.resolve('config');
  const logger = container.resolve('logger');
  const nodeEnv = config.get('server.nodeEnv');

  let tokenService = null;
  try {
    tokenService = container.resolve('tokenService');
  } catch (error) {
    logger.warn('User rate limiter: tokenService unavailable, relying on req.user only', {
      error: error.message
    });
  }

  const { windowMs, max } = getRateLimitConfig(nodeEnv, 'user');

  /**
   * Resolve the authenticated principal id, or null when the request is anonymous.
   * Memoized per request so skip() and keyGenerator() verify the token only once.
   * @param {Object} req - Express request
   * @returns {string|null}
   */
  const resolveUserId = (req) => {
    if (req.rateLimitUserId !== undefined) {
      return req.rateLimitUserId;
    }

    let userId = null;

    if (req.user?._id) {
      userId = req.user._id.toString();
    } else if (tokenService) {
      // Priority matches auth.middleware: httpOnly cookie > Authorization header
      let token = (req.cookies && req.cookies[COOKIE_NAMES.ACCESS_TOKEN]) || null;
      if (!token) {
        const authHeader = req.header('Authorization') || '';
        if (authHeader.startsWith('Bearer ')) {
          token = authHeader.slice('Bearer '.length);
        }
      }
      if (token) {
        try {
          const decoded = tokenService.verifyToken(token);
          userId = decoded && decoded.userId != null ? String(decoded.userId) : null;
        } catch (error) {
          // Invalid or expired token — treat as anonymous.
          userId = null;
        }
      }
    }

    req.rateLimitUserId = userId;
    return userId;
  };

  return rateLimit({
    windowMs,
    max,
    keyGenerator: (req) => resolveUserId(req),
    message: {
      success: false,
      error: {
        message: 'Too many requests from this account, please try again later',
        code: 'USER_RATE_LIMIT_EXCEEDED'
      }
    },
    standardHeaders: true,
    legacyHeaders: false,
    skip: (req) => {
      // Skip rate limiting for unauthenticated requests — never key them by IP here.
      return resolveUserId(req) === null;
    },
    handler: (req, res) => {
      logger.warn('User rate limit exceeded', {
        userId: resolveUserId(req),
        userType: req.userType,
        ip: req.ip,
        path: req.path,
        method: req.method,
        nodeEnv
      });
      res.status(429).json({
        success: false,
        error: {
          message: 'Too many requests from this account, please try again later',
          code: 'USER_RATE_LIMIT_EXCEEDED'
        }
      });
    }
  });
}

/**
 * Create strict rate limiting for sensitive endpoints
 * @param {Object} options - Rate limit options
 * @param {number} options.windowMs - Time window in milliseconds
 * @param {number} options.max - Maximum requests per window
 * @returns {Function} Express middleware
 */
function createStrictRateLimit(options = {}) {
  const windowMs = options.windowMs || 15 * 60 * 1000; // 15 minutes
  const max = options.max || 5; // 5 requests per window

  return rateLimit({
    windowMs,
    max,
    keyGenerator: (req) => {
      // Use user ID if authenticated, otherwise IP
      return req.user?._id?.toString() || req.headers['x-forwarded-for'] || req.socket.remoteAddress || 'unknown';
    },
    message: {
      success: false,
      error: {
        message: 'Too many attempts, please try again later',
        code: 'RATE_LIMIT_EXCEEDED'
      }
    },
    standardHeaders: true,
    legacyHeaders: false
  });
}

